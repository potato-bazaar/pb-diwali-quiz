const MESSAGES: Record<AppLanguage, typeof en> = { en, hi, gu, pa, mr, bn, te, ta, kn };

export type HomeMessageKey = keyof typeof en;

export function translateHome(lang: AppLanguage, key: HomeMessageKey, vars?: Record<string, string | number>) {
  const template = MESSAGES[lang][key] ?? en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}
